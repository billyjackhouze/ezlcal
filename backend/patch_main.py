    "    account_id: str | None = None\n"
    "    title: str = ''\n"
    "    email: str = ''\n"
    "    phone_direct: str = ''\n"
    "    phone_mobile: str = ''\n"
    "\n\n"
    "@app.post('/api/contacts')\n"
